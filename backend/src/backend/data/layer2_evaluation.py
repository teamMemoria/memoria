"""Test Layer 2 with the guidelines hidden.

Learns rules from the ABCD train calls without the guidelines, then checks
them against the guideline text afterwards: a rule counts as right if a
guideline in the same flow gives the same value (and names its membership
levels, if it has any). Also shows the rules growing as calls are added, and
scores the held-out test calls.

    uv run python -m backend.data.layer2_evaluation abcd_v1.1.json.gz guidelines.json

Both files are in https://github.com/asappresearch/abcd (data/). Don't commit
them.
"""

import argparse
import gzip
import json
import re
from collections import defaultdict
from pathlib import Path

from backend.data.value_claims import LEVELS, claims, values
from backend.entities.inferred_knowledge import Claim, Settings, Topic, score_call
from backend.use_cases.inferred_knowledge import LearnRules

OUT = Path(__file__).resolve().parents[3] / "results" / "layer2-eval.md"


class Calls:
    """A ``ClaimSource`` over claims already read from calls."""

    def __init__(self, claims: list[Claim]):
        self.items = claims

    def claims(self) -> list[Claim]:
        return self.items


def answer_key(guidelines: dict) -> dict[str, list[tuple[str, set[str]]]]:
    """(value, levels) pairs the guidelines give, per flow."""
    key = defaultdict(list)
    for title, flow in guidelines.items():
        flow_id = re.sub(r"[^a-z]+", "_", title.lower())
        texts = [t for sub in flow["subflows"].values() for t in sub["instructions"]]
        for sub in flow["subflows"].values():
            for action in sub["actions"]:
                texts += [action["text"], *action.get("subtext", [])]
        for text in texts:
            levels = {level for level in LEVELS if level in text.lower()}
            key[flow_id] += [(value, levels) for value in values(text)]
    return key


def is_checkable(topic: Topic, flow: str, key: dict) -> bool:
    """The guidelines for this flow give at least one value in the rule's unit."""
    return any(v.split(" ", 1)[1] == topic.scope[2] for v, _ in key.get(flow, []))


def is_right(topic: Topic, flow: str, key: dict) -> bool:
    levels = set(topic.scope[1])
    return any(v == topic.rule and levels <= lv for v, lv in key.get(flow, []))


def evaluate(dump: dict, guidelines: dict, sizes=(500, 1000, 2000, 4000)) -> str:
    flow_of = {r["scenario"]["subflow"]: r["scenario"]["flow"] for r in dump["train"]}
    key = answer_key(guidelines)
    train = [claims(r) for r in dump["train"]]
    lines = [
        "# Layer 2: hidden-guidelines test",
        "",
        (
            "Generated by `python -m backend.data.layer2_evaluation`. Learned from ABCD train calls "
            "(agent speech only) without the guidelines."
        ),
        "",
        "| Calls | Rules | Conflicts | Checkable rules | Right |",
        "|---|---|---|---|---|",
    ]
    for n in [n for n in sizes if n < len(train)] + [len(train)]:
        topics = LearnRules(Calls([c for call in train[:n] for c in call])).execute()
        rules = [t for t in topics if t.decide(Settings()) == "rule"]
        # Two topics can end up with the same rule; count it once.
        rules = list({(t.scope, t.rule): t for t in rules}.values())
        checkable = [t for t in rules if is_checkable(t, flow_of[t.scope[0]], key)]
        right = sum(is_right(t, flow_of[t.scope[0]], key) for t in checkable)
        conflicts = [t for t in topics if t.decide(Settings()) == "conflict"]
        lines.append(
            f"| {n} | {len(rules)} | {len(conflicts)} | {len(checkable)} | {right} |"
        )

    scores = [score_call(claims(r), topics) for r in dump["test"]]
    matches, differs = (
        sum(s["matches"] for s in scores),
        sum(s["differs"] for s in scores),
    )
    lines += [
        "",
        (
            f"Held out: {len(dump['test'])} test calls, {matches} rules matched, "
            f"{differs} differed."
        ),
        "",
        "## Rules",
        "",
        "| Category | Levels | Value | Calls | Guidelines | Example |",
        "|---|---|---|---|---|---|",
    ]
    for t in sorted(rules, key=lambda t: (t.scope, t.rule)):
        flow = flow_of[t.scope[0]]
        check = (
            "right"
            if is_right(t, flow, key)
            else "not in them"
            if is_checkable(t, flow, key)
            else "-"
        )
        example = t.example[t.rule].replace("|", "/")[:90]
        levels = ", ".join(t.scope[1]) or "-"
        calls = len(t.values_by_call)
        lines.append(
            f"| {t.scope[0]} | {levels} | {t.rule} | {calls} | {check} | {example} |"
        )
    lines += ["", "## Conflicts for a manager", ""]
    for t in conflicts:
        lines.append(
            f"- {t.scope[0]}: " + ", ".join(f"{v} ({n})" for v, n in t.votes()[:4])
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("abcd", type=Path, help="abcd_v1.1.json.gz")
    parser.add_argument("guidelines", type=Path, help="guidelines.json")
    args = parser.parse_args()
    with gzip.open(args.abcd, "rt") as f:
        dump = json.load(f)
    report = evaluate(dump, json.loads(args.guidelines.read_text()))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
